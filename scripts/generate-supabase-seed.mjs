import { mkdirSync, writeFileSync } from 'node:fs';

// Export only the public preview catalog; never query orders, users, or admin APIs.
const response = await fetch('http://127.0.0.1:3000/api/store', {
  signal: AbortSignal.timeout(15000),
});
if (!response.ok) throw new Error(`Catalog request failed: ${response.status}`);
const catalog = await response.json();
if (catalog.settings?.mode !== 'preview' || !Array.isArray(catalog.products))
  throw new Error('Seed generation requires a public catalog in preview mode.');
if (catalog.products.some((product) => product.demo !== true))
  throw new Error('Refusing to export non-demo products.');

const pick = (value, keys) =>
  Object.fromEntries(
    keys.filter((key) => Object.hasOwn(value, key)).map((key) => [key, value[key]]),
  );
const settings = pick(catalog.settings, [
  'brand',
  'mode',
  'heroTitle',
  'heroSubtitle',
  'heroImage',
  'heroVideo',
  'storyTitle',
  'storyText',
  'contactPhone',
  'contactEmail',
  'address',
  'shippingPolicy',
  'returnsPolicy',
  'privacyPolicy',
  'codEnabled',
  'sections',
  'branches',
  'shippingZones',
]);
const uuid = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const ids = new Set();
const products = catalog.products.map((item) => {
  if (!uuid.test(item.id) || ids.has(item.id))
    throw new Error('Invalid or duplicate product UUID.');
  ids.add(item.id);
  const product = pick(item, [
    'id',
    'slug',
    'name',
    'description',
    'roast',
    'brew',
    'kind',
    'grinds',
    'image',
    'active',
    'featured',
    'demo',
    'stockMode',
    'stockGrams',
    'updatedAt',
  ]);
  if (!Array.isArray(item.variants) || item.variants.length === 0)
    throw new Error('Every demo product must have variants.');
  product.variants = item.variants.map((variant) => {
    if (!uuid.test(variant.id)) throw new Error('Invalid variant UUID.');
    for (const field of ['weight', 'price', 'stock']) {
      if (!Number.isSafeInteger(variant[field]) || variant[field] < 0)
        throw new Error(`Invalid variant ${field}.`);
    }
    if (variant.weight === 0) throw new Error('Variant weight must be positive.');
    return pick(variant, ['id', 'weight', 'price', 'stock']);
  });
  return product;
});
const sqlString = (value) => `'${String(value).replaceAll("'", "''")}'`;
const jsonb = (value) => `${sqlString(JSON.stringify(value))}::jsonb`;
const statements = [
  '-- Dar El Bon public demo catalog. Generated by scripts/generate-supabase-seed.mjs.',
  '-- Prices remain integer piasters; no orders, authentication users, or admin records are exported.',
  '-- Existing rows are preserved: ON CONFLICT DO NOTHING.',
  'BEGIN;',
  'SET LOCAL standard_conforming_strings = on;',
  `INSERT INTO public.dar_settings (id, value) VALUES (1, ${jsonb(settings)}) ON CONFLICT (id) DO NOTHING;`,
  ...products.map(
    (product) =>
      `INSERT INTO public.dar_products (id, data) VALUES (${sqlString(product.id)}::uuid, ${jsonb(product)}) ON CONFLICT (id) DO NOTHING;`,
  ),
  'COMMIT;',
  '',
];
mkdirSync('supabase', { recursive: true });
writeFileSync('supabase/seed.sql', statements.join('\n'), { mode: 0o600 });
console.log(
  `Created supabase/seed.sql with ${products.length} demo products and public settings; existing rows will be preserved.`,
);
